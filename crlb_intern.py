def generalized_crlb(theta, log_likelihood, data, eps=1e-6):

    # ---- SCORE FUNCTION (DERIVATIVE OF LOG-LIKELIHOOD) ----
    def score(theta, x):
        return (log_likelihood(theta + eps, x) -
                log_likelihood(theta - eps, x)) / (2 * eps)

    # ---- COMPUTE SCORE FOR ALL DATA REALIZATIONS ----
    scores = np.array([score(theta, x) for x in data])

    # ---- FISHER INFORMATION (EXPECTATION OF SCORE^2) ----
    fisher_information = np.mean(scores**2)

    # ---- CRAMÉR–RAO LOWER BOUND ----
    crlb = 1 / fisher_information

    return crlb

