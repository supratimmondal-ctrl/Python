#  Model log-likelihoods & vectorized score functions
SQRT2PI = np.sqrt(2 * np.pi)

def gaussian_loglike(theta: float, x: np.ndarray, sigma: float = 1.0) -> np.ndarray:
    z = (x - theta) / sigma
    return -0.5 * z**2 - np.log(sigma * SQRT2PI)

def gaussian_score(theta: float, x: np.ndarray, sigma: float = 1.0) -> np.ndarray:
    return (x - theta) / (sigma ** 2)

def laplace_loglike(theta: float, x: np.ndarray, b: float = 1.0) -> np.ndarray:
    return - np.abs(x - theta) / b - np.log(2 * b)

def laplace_score(theta: float, x: np.ndarray, b: float = 1.0) -> np.ndarray:
    s = np.sign(x - theta)
    return s / b

def exp_power_loglike(theta: float, x: np.ndarray, sigma: float = 1.0, beta: float = 2.0) -> np.ndarray:
    z = np.abs(x - theta) / sigma
    return - (z ** beta) - np.log(sigma)

def exp_power_score(theta: float, x: np.ndarray, sigma: float = 1.0, beta: float = 2.0) -> np.ndarray:
    diff = x - theta
    absdiff = np.abs(diff)
    with np.errstate(divide='ignore', invalid='ignore'):
        term = beta * np.sign(diff) * (absdiff / sigma) ** (beta - 1) / sigma
    term = np.where(absdiff == 0.0, 0.0, term)
    return term

